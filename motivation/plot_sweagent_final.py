def paired_cost_data(data):
    """Keep the full matched population for each individual control."""
    rows = []
    for key in COHORTS:
        for control in CONTROLS:
            if control not in data["cohorts"][key]["comparisons"]:
                continue
            comparison = data["cohorts"][key]["comparisons"][control]
            pairs = comparison["pairs"]
            agent_tokens = sum(pair["causal_tokens"] for pair in pairs)
            control_tokens = sum(pair["control_tokens"] for pair in pairs)
            assert len(pairs) == comparison["n"]
            assert agent_tokens == comparison["causal_tokens"]
            assert control_tokens == comparison["control_tokens"]
            saved_tokens = control_tokens-agent_tokens
            saving_pct = 100*saved_tokens/control_tokens
            assert np.isclose(saving_pct, comparison["saving_pct"])
            rows.append(dict(cohort=key, control=control, n=len(pairs),
                             agenttx_tokens=int(agent_tokens), control_tokens=int(control_tokens),
                             saved_tokens=int(saved_tokens), saving_pct=float(saving_pct),
                             ci95_pct=comparison["ci95_pct"],
                             tasks=[dict(task=p["task"], configuration_id=p["configuration_id"])
                                    for p in pairs]))
    return rows


def plot_summary(data, time_data):
    """Plot cumulative totals with the established four-panel line style."""
    controls = ("turn_checkpoint", "temporal_checkpoint", "whole_branch_abort")
    policies = ("causal", *controls)
    headings = ("SWE / SWE-agent", "SWE / Codex", "TB / SWE-agent", "TB / Codex")
    fig, axes = plt.subplots(2, 2, figsize=(8.5*CM, 7.2*CM), dpi=300)
    audit = []
    for row, key in enumerate(COHORTS):
        token_pairs = {p: {(r["configuration_id"], r["task"]): r
                           for r in data["cohorts"][key]["comparisons"][p]["pairs"]}
                       for p in controls}
        time_pairs = {p: {(r["configuration_id"], r["task"]): r
                          for r in time_data["cohorts"][key][p]["pairs"]}
                      for p in controls}
        common = set.intersection(*(set(m) for m in (*token_pairs.values(), *time_pairs.values())))
        tasks = sorted(common, key=lambda identity: (identity[1], identity[0]))
        assert tasks and len({task for _, task in tasks}) == len(tasks)
        for identity in tasks:
            assert len({token_pairs[p][identity]["causal_tokens"] for p in controls}) == 1
            assert len({time_pairs[p][identity]["causal_s"] for p in controls}) == 1
        x = np.unique(np.r_[np.arange(25, len(tasks)+1, 25), len(tasks)]).astype(int)
        values = {p: np.array([token_pairs[p][identity]["control_tokens"] for identity in tasks], dtype=float)
                  for p in controls}
        values["causal"] = np.array([token_pairs[controls[0]][identity]["causal_tokens"]
                                     for identity in tasks], dtype=float)
        baseline = np.cumsum(values["temporal_checkpoint"])
        points = {}
        ax = axes.flat[row]
        for policy in (*controls, "causal"):
            cumulative = np.cumsum(values[policy])
            saving = 100*(1-cumulative/baseline)
            ax.plot(np.r_[0, x], np.r_[0, cumulative[x-1]/1e6], **STYLES[policy])
            points[policy] = dict(tokens=dict(total=float(cumulative[-1]),
                                              cumulative=np.r_[0, cumulative].tolist()),
                                  saving_pct=saving.tolist(),
                                  plotted_points=[dict(tasks=int(n), total_tokens=float(cumulative[n-1]),
                                                       saving_pct=float(saving[n-1])) for n in x])
        agent_total = points["causal"]["tokens"]["total"]
        reference_total = points["temporal_checkpoint"]["tokens"]["total"]
        saved = reference_total-agent_total
        ax.text(.04, .96, f"−{100*saved/reference_total:.1f}% tokens",
                transform=ax.transAxes, ha="left", va="top", fontsize=6.3,
                color=STYLES["causal"]["color"])
        ax.set_title(f"({chr(97+row)}) {headings[row]}", fontsize=8, pad=4)
        ax.set_xlabel("Completed tasks", fontsize=7.5, labelpad=3)
        ax.set_ylabel("Total tokens (M)", fontsize=7.5, labelpad=3)
        ax.set_xlim(0, len(tasks))
        ax.set_xticks([0, len(tasks)//2, len(tasks)])
        ax.set_ylim(0, max(point["tokens"]["total"] for point in points.values())/1e6*1.18)
        ax.yaxis.set_major_locator(MaxNLocator(nbins=4, min_n_ticks=3))
        ax.grid(False)
        frame(ax)
        audit.append(dict(cohort=key, n=len(tasks), reference_policy="temporal_checkpoint",
                          tasks=[dict(configuration_id=cid, task=task) for cid, task in tasks],
                          policies=points))
    handles = [Line2D([], [], label=LABELS[p],
                      **STYLES[p]) for p in policies]
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(.54, 1.005), ncol=2,
               fontsize=7, borderpad=.35, columnspacing=1, handlelength=1.8,
               handletextpad=.45, labelspacing=.4)
    fig.subplots_adjust(left=.15, right=.985, bottom=.11, top=.83, wspace=.40, hspace=.58)
    return save(fig, "FIG-SWEagent-SWEbench-Results"), audit


def paired_time_data(data, token_data):
    """Use the token comparisons' task populations for workflow time."""
    rows = []
    for key in COHORTS:
        for control in CONTROLS:
            if control not in data["cohorts"][key]:
                continue
            comparison = data["cohorts"][key][control]
            pairs = comparison["pairs"]
            identity = lambda pair: (pair["configuration_id"], pair["task"])
            token_pairs = token_data["cohorts"][key]["comparisons"][control]["pairs"]
            assert {identity(p) for p in pairs} == {identity(p) for p in token_pairs}
            assert len(pairs) == comparison["n"] == len(token_pairs)
            agent_seconds = sum(p["causal_s"] for p in pairs)
            control_seconds = sum(p["control_s"] for p in pairs)
            assert np.isclose(agent_seconds, comparison["causal_total_s"])
            assert np.isclose(control_seconds, comparison["control_total_s"])
            saving_pct = 100 * (1 - agent_seconds / control_seconds)
            assert np.isclose(saving_pct, comparison["saving_pct"])
            rows.append(dict(cohort=key, control=control, n=len(pairs),
                             agenttx_mean_s=agent_seconds / len(pairs),
                             control_mean_s=control_seconds / len(pairs),
                             saved_mean_s=(control_seconds-agent_seconds) / len(pairs),
                             saving_pct=saving_pct, ci95_pct=comparison["ci95_pct"]))
    return rows


def plot_paired_savings(rows, metric):
    """Share the same layout and policy colors for token and time bars."""
    if metric == "tokens":
        agent_field, control_field, saved_field = "agenttx_tokens", "control_tokens", "saved_tokens"
        divisor, unit, axis_label = 1e6, "M", "Total tokens (M)"
        stem = "FIG-Realworld-Token-Savings"
        value_format = ".2f"
    else:
        assert metric == "time"
        agent_field, control_field, saved_field = "agenttx_mean_s", "control_mean_s", "saved_mean_s"
        divisor, unit, axis_label = 1, "s", "Mean workflow time (s)"
        stem = "FIG-Realworld-Time-Savings"
        value_format = ".1f"
    headings = ("SWE / SWE-agent", "SWE / Codex", "TB / SWE-agent", "TB / Codex")
    fig, axes = plt.subplots(2, 2, figsize=(8.5*CM, 6.8*CM), dpi=300)
    short_labels = LABELS
    for panel, (key, heading) in enumerate(zip(COHORTS, headings)):
        ax = axes.flat[panel]
        group = {row["control"]: row for row in rows if row["cohort"] == key}
        controls = [p for p in CONTROLS if p in group]
        positions = list(reversed(range(len(controls))))
        maximum = max(group[p][field] for p in controls
                      for field in (agent_field, control_field)) / divisor
        labels = []
        for y, control in zip(positions, controls):
            row = group[control]
            label = short_labels[control]
            labels.append(f"{label}\n(n={row['n']})")
            for offset, policy, field in ((.20, "causal", agent_field),
                                           (-.20, control, control_field)):
                value = row[field] / divisor
                ax.barh(y+offset, value, height=.28,
                        color=BAR_POLICY_COLORS[policy], linewidth=0)
                ax.text(value+maximum*.025, y+offset, format(value, value_format),
                        ha="left", va="center", fontsize=6)
            annotation = f"{row[saved_field]/divisor:{value_format}} {unit}\n({row['saving_pct']:.2f}%)"
            ax.text(1.28, y, annotation.replace("-", "−"),
                    transform=ax.get_yaxis_transform(), ha="center", va="center",
                    fontsize=6.2, linespacing=1.05)
        ax.set_yticks(positions, labels)
        ax.set_ylim(-.55, len(controls)-.45)
        ax.set_xlim(0, maximum*1.5)
        ax.xaxis.set_major_locator(MaxNLocator(nbins=3, min_n_ticks=3))
        ax.set_title(f"({chr(97+panel)}) {heading}", fontsize=7.5, pad=4)
        frame(ax)
        ax.tick_params(axis="y", length=0, pad=2, labelsize=6.2)
        ax.tick_params(axis="x", labelsize=6.5)
        ax.tick_params(axis="x", top=False)
        ax.spines[["top", "right", "left"]].set_visible(False)
    legend_labels = LABELS
    handles = [Patch(facecolor=BAR_POLICY_COLORS[p], label=legend_labels[p])
               for p in ("causal", *CONTROLS) if any(p == "causal" or r["control"] == p for r in rows)]
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(.52, 1.005),
               ncol=3, fontsize=6.5, borderpad=.3, columnspacing=1,
               handlelength=1.2, handletextpad=.4, labelspacing=.3)
    fig.supxlabel(axis_label, fontsize=7.5, y=-.01)
    fig.subplots_adjust(left=.17, right=.85, bottom=.10, top=.79,
                        wspace=1.20, hspace=.60)
    return save(fig, stem)


