#!/usr/bin/env python3
"""Compatibility entry point for the official application token benchmark.

The complete agent trajectory is the official task itself.  Recovery policy
comparisons are recorded in ``official_token_summary.csv``; no synthetic
``document_lines`` workload is generated here.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

from experiments.scripts.bench_official_tasks import HARNESSES, MODES, main as official_main  # noqa: E402


def recovery_task(document_lines: int) -> str:
    """Return the historical contract text used by unit tests.

    The executable benchmark no longer creates this synthetic repository; the
    helper remains to keep validation tests for recovery semantics stable.
    """
    return f"""A filesystem recovery policy has already been applied. Diagnose and finish recovery.
1. Run the tests.
2. If a document fails validation, recreate only that document.
3. docs/design.md must contain exactly {document_lines} ordered entries DESIGN-001: through DESIGN-{document_lines:03d}:.
4. docs/changelog.md must contain exactly {document_lines} ordered entries CHANGE-001: through CHANGE-{document_lines:03d}:.
5. Preserve every valid document.
6. Ensure derived artifacts are absent and the tests pass.
7. Do not call a rollback tool: the comparison policy has already run.
8. Call finish with commit=false when done.
"""


def regenerated_documents(steps, first_step: int):
    """Return documents regenerated by non-rolled-back write_file effects."""
    found = set()
    for step in steps[first_step:]:
        if getattr(step, "tool_name", "") != "write_file" or getattr(step, "status", "") == "rolled_back":
            continue
        for effect in getattr(step, "effects", []):
            normalized = getattr(effect, "path", "").lstrip("./")
            for relative in ("docs/design.md", "docs/changelog.md"):
                if normalized == relative or normalized.endswith("/" + relative):
                    found.add(relative)
    return [path for path in ("docs/design.md", "docs/changelog.md") if path in found]


def summarize(rows):
    """Summarize historical-shaped rows for compatibility tests only."""
    by_mode = {row["mode"]: row for row in rows}
    causal = by_mode.get("causal", {})
    base_total = float(causal.get("total_tokens", 0) or 0)
    base_completion = float(causal.get("completion_tokens", 0) or 0)
    out = []
    for mode, row in by_mode.items():
        total = float(row.get("total_tokens", 0) or 0)
        completion = float(row.get("completion_tokens", 0) or 0)
        saved = total - base_total if mode != "causal" else 0.0
        completion_saved = completion - base_completion if mode != "causal" else 0.0
        item = dict(row)
        item.update(
            agenttx_total_tokens_saved=int(saved),
            agenttx_total_tokens_saved_pct=round(saved / total, 3) if total else 0.0,
            agenttx_completion_tokens_saved=int(completion_saved),
        )
        out.append(item)
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Run official SWE-Bench Lite + Terminal-Bench end-to-end token evaluation."
    )
    parser.add_argument("--harness", choices=HARNESSES, default="deepseek_harness")
    parser.add_argument("--suite", choices=("swe", "tb", "all"), default="all")
    parser.add_argument("--repeats", type=int, default=1)
    parser.add_argument("--modes", nargs="+", choices=MODES, default=list(MODES))
    parser.add_argument("--max-turns", type=int, default=None)
    parser.add_argument("--model", default=None)
    parser.add_argument("--trace-backend", choices=("strace", "bpf_persistent"), default="strace")
    parser.add_argument("--preflight-only", action="store_true")
    args = parser.parse_args(argv)
    forwarded = [
        "--harness", args.harness, "--suite", args.suite,
        "--repeats", str(args.repeats), "--modes", *args.modes,
        "--trace-backend", args.trace_backend,
    ]
    if args.max_turns is not None:
        forwarded += ["--max-turns", str(args.max_turns)]
    if args.model:
        forwarded += ["--model", args.model]
    if args.preflight_only:
        forwarded.append("--preflight-only")
    return official_main(forwarded)


if __name__ == "__main__":
    raise SystemExit(main())
